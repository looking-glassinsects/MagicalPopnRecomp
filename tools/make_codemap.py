"""Maintainer tool: build data/codemap.txt, the list of code entry points shipped with the repo.

Runs many long bot sessions of the trace profiler in parallel on a ROM, merges the entries
(plus any discovered.txt files given), and writes each entry with a fingerprint of the code
bytes at that address. The builder uses entries whose fingerprint matches the user's ROM, so
known versions of the game need no profiling at all. No game data is stored: only addresses,
register widths and 32-bit checksums.

    python tools/make_codemap.py ROM --label NAME [--sessions N] [--minutes M] [entries.txt | profile_dir ...]

Each version of the game gets its own label; rows already in the map are kept unchanged, so
running it once per version builds one map that recognises all of them.
"""
import argparse
import concurrent.futures as cf
import os
import pathlib
import subprocess
import sys
import zlib

TOOLS = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import msvc                                    # noqa: E402
import snes                                    # noqa: E402
import pipeline as P                           # noqa: E402
from disasm65816 import read_entries           # noqa: E402

CODEMAP = P.REPO / "data" / "codemap.txt"
FP_LEN = 12


def fingerprint(rom, addr):
    fo = snes.lorom_to_file(addr)
    if fo is None or fo >= len(rom):
        return None
    return f"{zlib.crc32(rom[fo:fo + FP_LEN]) & 0xFFFFFFFF:08x}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("--sessions", type=int, default=24)
    ap.add_argument("--minutes", type=int, default=30)
    ap.add_argument("--label", required=True, help="short name of this version, e.g. fastrom or original")
    ap.add_argument("extra", nargs="*", help="more entry files, or folders of them (e.g. a builder profile)")
    a = ap.parse_args()
    rom, info = snes.load(a.rom)
    work = P.REPO / "build" / f"codemap-{info['sha1'][:12]}"
    work.mkdir(parents=True, exist_ok=True)
    (work / "rom.sfc").write_bytes(rom)
    tracer = P.build_tracer(log=print)
    frames = a.minutes * 3600
    sessions = [("attract", 1, 36000), ("menus", 1, frames // 2), ("menus", 2, frames // 2), ("menus", 3, frames // 2)]
    sessions += [("play", 100 + s, frames) for s in range(a.sessions)]
    outs = []

    def run(sess):
        mode, seed, fr = sess
        o = work / f"{mode}_{seed}_{fr}.txt"
        if not o.exists():
            subprocess.run([str(tracer), str(work / "rom.sfc"), str(o), mode, str(seed), str(fr)],
                           check=True, capture_output=True)
        return o

    with cf.ThreadPoolExecutor(max(1, (os.cpu_count() or 4) - 2)) as ex:
        for i, o in enumerate(ex.map(run, sessions)):
            outs.append(o)
            print(f"session {i + 1}/{len(sessions)} done", flush=True)
    extra = []
    for p in a.extra:                      # entry files, or folders of them (a builder profile)
        p = pathlib.Path(p)
        extra += sorted(p.glob("*.txt")) if p.is_dir() else [p]
    entries = set(read_entries(outs + extra))

    # rows already in the map stay exactly as they are (they belong to other versions); this
    # ROM's entries are added under its label, sharing a row where the code is identical
    rows = {}                              # (addr, m, x, fp) -> set of version labels
    if CODEMAP.exists():
        for line in CODEMAP.read_text().splitlines():
            parts = line.split()
            if len(parts) >= 4 and not line.startswith("#"):
                key = (int(parts[0], 16), int(parts[1]), int(parts[2]), parts[3])
                rows.setdefault(key, set()).update(parts[4].split(",") if len(parts) > 4 else ["fastrom"])
    before = {k: set(v) for k, v in rows.items()}
    for (addr, m, x) in entries:
        fp = fingerprint(rom, addr)
        if fp:
            rows.setdefault((addr, m, x, fp), set()).add(a.label)
    for key in before:                     # known entries whose code this ROM shares
        if a.label not in rows[key] and fingerprint(rom, key[0]) == key[3]:
            rows[key].add(a.label)
    CODEMAP.parent.mkdir(exist_ok=True)
    CODEMAP.write_text("# Magical Pop'n code entry points: address, M flag, X flag, crc32 of the first "
                       f"{FP_LEN} code bytes, versions of the game it was found in.\n"
                       "# Generated by tools/make_codemap.py; contains no game data.\n"
                       + "".join(f"{k[0]:06X} {k[1]} {k[2]} {k[3]} {','.join(sorted(v))}\n" for k, v in sorted(rows.items())))
    mine = sum(1 for v in rows.values() if a.label in v)
    print(f"{len(rows)} entries ({mine} for '{a.label}') -> {CODEMAP}")


if __name__ == "__main__":
    main()
